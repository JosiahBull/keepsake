//! The handler: which tools exist for this profile right now, and what it says it is.

use keepsake_core::{agent_access, profiles::Profile};
use rmcp::handler::server::tool::{ToolCallContext, ToolRouter};
use rmcp::model::{
    CacheScope, CallToolRequestParams, CallToolResponse, Implementation, ListToolsResult,
    PaginatedRequestParams, ProtocolVersion, ResultType, ServerCapabilities, ServerConfig, Tool,
};
use rmcp::service::RequestContext;
use rmcp::{ErrorData, RoleServer, ServerHandler};
use sqlx::SqlitePool;

use crate::config::McpMode;
use crate::error::internal;

/// One profile's library. The transport builds one per request.
#[derive(Clone)]
pub struct KeepsakeMcp {
    pub(crate) pool: SqlitePool,
    pub(crate) ceiling: McpMode,
    pub(crate) profile: Profile,
}

impl KeepsakeMcp {
    pub fn new(pool: SqlitePool, ceiling: McpMode, profile: Profile) -> Self {
        Self {
            pool,
            ceiling,
            profile,
        }
    }

    /// The tools `mode` serves.
    ///
    /// Write tools are added here or not at all, never registered and then checked: a
    /// check inside each handler is one forgotten `if` from a silent write. Exhaustive,
    /// so a new mode has to say what it serves.
    pub fn router_for(mode: McpMode) -> ToolRouter<Self> {
        match mode {
            // Nothing at all, not read-only: the profile switched agent access off.
            McpMode::Off => ToolRouter::new(),
            McpMode::Read => Self::library_router(),
            McpMode::Write => Self::router_for(McpMode::Read) + Self::capture_router(),
        }
    }

    /// The profile's chosen mode, clamped to the environment's ceiling.
    ///
    /// Read on every request, so switching access off in the app applies to the next
    /// call with no cache to go stale in the permissive direction.
    pub async fn effective_mode(&self) -> Result<McpMode, ErrorData> {
        match self.ceiling {
            // Nothing can raise off, so there is no setting to read.
            McpMode::Off => Ok(McpMode::Off),
            McpMode::Read | McpMode::Write => {
                let stored = agent_access::mode(&self.pool, self.profile.id)
                    .await
                    .map_err(internal)?;
                Ok(self.ceiling.min(stored))
            }
        }
    }
}

/// Written out rather than generated by `#[tool_handler]`, which fixes one router when
/// the handler is built. Here the router follows a setting the learner can change.
impl ServerHandler for KeepsakeMcp {
    fn get_info(&self) -> ServerConfig {
        let mut info = ServerConfig::new(ServerCapabilities::builder().enable_tools().build());
        info.server_info = Implementation::new("keepsake", env!("CARGO_PKG_VERSION"))
            .with_title(format!("Keepsake: {}'s library", self.profile.name));
        info.instructions = Some(instructions(&self.profile.name));
        info
    }

    async fn call_tool(
        &self,
        request: CallToolRequestParams,
        context: RequestContext<RoleServer>,
    ) -> Result<CallToolResponse, ErrorData> {
        // The only gate: a tool the current mode does not serve is not in this router.
        Self::router_for(self.effective_mode().await?)
            .call(ToolCallContext::new(self, request, context))
            .await
    }

    async fn list_tools(
        &self,
        _request: Option<PaginatedRequestParams>,
        context: RequestContext<RoleServer>,
    ) -> Result<ListToolsResult, ErrorData> {
        let mut result = ListToolsResult::with_all_items(
            Self::router_for(self.effective_mode().await?).list_all(),
        );
        // The list changes when the learner flips a switch, so clients must not cache it.
        if context
            .protocol_version()
            .is_some_and(|version| version >= ProtocolVersion::V_2026_07_28)
        {
            result.ttl_ms = Some(0);
            result.cache_scope = Some(CacheScope::Public);
        }
        result.result_type = Some(ResultType::COMPLETE);
        Ok(result)
    }

    /// The transport reads this only for a tool's input schema, so it answers from the
    /// ceiling. A schema is not permission; `call_tool` decides what runs.
    fn get_tool(&self, name: &str) -> Option<Tool> {
        Self::router_for(self.ceiling).get(name).cloned()
    }
}

fn instructions(name: &str) -> String {
    format!(
        "Keepsake is a personal flashcard library. Each fact has a question and an answer, \
optionally with context, a source, tags, and images or audio clips asked with the question. \
The learner practises facts on a spaced schedule. This connection reaches {name}'s library only.

- search_facts finds facts; get_fact shows one in full, with its practice variants and media; \
view_media returns a question's image or clip.
- list_tags shows the tags in use. Reuse them: matching practice draws related facts from one tag.
- study_overview says what is ready to study. The learner reviews and rates answers in the \
Keepsake app, attempting each before seeing it; no tool records a review.
- With write access, add_facts saves facts and add_practices adds practice variants. Check each \
fact against its source and record that source. Phrase a question so one answer is correct. \
Images and clips belong to the question and must not show the answer.
- New variants are unchecked: they appear in extra practice, and count towards scheduled recall \
only after the learner approves them with `keepsake study approve`.

The tools can change while you are connected: the learner can turn agent access off, or down to \
read-only, in their profile settings. If a tool you saw earlier no longer exists, list the tools again."
    )
}
